#!/bin/bash
# =============================================================================
# runner.sh — оркестратор установки
# Версия: v1.0.2
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Центральный оркестратор, который:
#     1) Подключает общие библиотеки (log/wipe/disk/fs/efi).
#     2) Находит и последовательно выполняет все шаги из steps/ по маске NN_*.sh.
#     3) В конце запускает OS-специфичный chroot-скрипт os/${OS}/80_chroot.sh.
#
# Контекст:
#   Переменные окружения (включая backup_ip/backup_passwd/backup_dir/OS) уже
#   подготовлены auto_install.sh и доступны здесь.
#   Все шаги выполняются в одном shell-контексте, что позволяет:
#     • использовать общие функции из lib/*.sh;
#     • выставлять переменные в ранних шагах и использовать их в последующих.
# =============================================================================

# Жёсткий режим: падать при ошибке/необъявленной переменной/ошибке в конвейере
set -euo pipefail

# ------------------------- Базовый путь бандла -------------------------------
# Абсолютный путь к каталогу /root/deploy (где лежит этот runner и остальные файлы)
BASE_DIR="$(cd "$(dirname "$0")" && pwd)"

# --------------------------- Настройки оболочки ------------------------------
# Если в каталоге нет совпадений по шаблону, не подставлять текст шаблона:
# иначе "steps/*" превратится в строку "steps/*" и сломает логику.
shopt -s nullglob

# --------------------------- Подключение библиотек ---------------------------
# Общие функции, которые используют шаги (логирование, вайп, разметка дисков,
# создание ФС и подготовка EFI-загрузки). Подключаем через "source" в текущий
# контекст, чтобы функции и переменные были доступны всем шагам.
. "$BASE_DIR/lib/log.sh"
. "$BASE_DIR/lib/wipe.sh"
. "$BASE_DIR/lib/disk.sh"
. "$BASE_DIR/lib/fs.sh"
. "$BASE_DIR/lib/efi.sh"

# ------------------------- Надёжность и логирование --------------------------
# Трап для логирования ошибок: срабатывает при ненулевом коде завершения.
# Использует переменную STEP_NAME, которую выставляем перед каждым шагом.
fail_trap() {
  log_level "ERROR" "Execution FAILED on step: ${STEP_NAME:-<unknown>}"
}
trap 'fail_trap' ERR

# Имя шага по умолчанию (пока не зашли в конкретный файл)
STEP_NAME="runner"

# ------------------------------ Поиск шагов ----------------------------------
# Собираем список файлов-шагов по маске NN_name.sh (например, 00_env.sh, 30_*).
# Благодаря nullglob выше — если файлов нет, массив будет пустым.
steps=( "$BASE_DIR/steps/"[0-9][0-9]_*.sh )

# Если шагов нет — это ошибка сборки бандла (нечего выполнять).
if [ ${#steps[@]} -eq 0 ]; then
  log_level "ERROR" "No steps found in $BASE_DIR/steps"
  exit 1
fi

# ---------------------------- Выполнение шагов -------------------------------
# Последовательно "source"-им каждый шаг.
# ВАЖНО: именно source (а не exec/bash), чтобы шаги видели общее окружение
# и могли пользоваться функциями из библиотек, а также выставлять переменные
# для последующих шагов.
for step in "${steps[@]}"; do
  STEP_NAME="$(basename "$step")" # Устанавливаем имя шага для трассировки
  log "--- run step: ${STEP_NAME}"
  . "$step"
done

# ------------------------- Финальный OS-спец. этап ---------------------------
# Запуск chroot-скрипта, специфичного для выбранной ОС (ALT/RedOS и т.д.).
STEP_NAME="80_chroot_${OS}"
. "$BASE_DIR/os/${OS}/80_chroot.sh"

# Сброс трапа после успешного завершения runner.sh
trap - ERR

