# Назначение шага:
#   Базовая подготовка окружения перед выполнением остальных шагов пайплайна:
#     1) (Опционально) переключает вывод в «ранний» лог (early_log) на LiveCD.
#     2) Включает жёсткий режим оболочки (ошибка → выход).
#     3) Устанавливает временный hostname (если задан meta_hostname), чтобы
#        mdadm/LVM фиксировали именно его в метаданных.
#     4) Логирует ключевые параметры конфигурации (для последующей трассировки).
#
# Контекст / предпосылки:
#   - Шаг вызывается runner.sh уже после подключения библиотек log.sh/wipe.sh/…
#   - Переменные early_log, OS, min_size_gb, max_size_gb, esp_mb, boot_mb,
#     swap_mb, vg_name, use_varlog_disk, meta_hostname экспортируются
#     из install.env auto_install.sh-скриптом.
# =============================================================================

# ➊ Переключение stdout/stderr в ранний лог (на LiveCD) с дублированием в консоль.
#    Текущее поведение оставлено выключенным намеренно:
#      • логирование уже настроено в auto_install.sh (/tmp/deploy.log);
#      • при необходимости можно включить этот механизм, раскомментировав exec
#        или добавив управление через переменную окружения (см. предложения ниже).
#exec > >(tee -a "$early_log") 2>&1

# ➋ «Жёсткий» режим выполнения: любая ошибка команды / обращение к
#    необъявленной переменной / ошибка в конвейере → немедленный выход.
set -euo pipefail

# ➌ Один раз задаём hostname на время инсталляции.
#    Это имя попадёт в метаданные mdadm/LVM и поможет отличать источник сборки.
#    Если meta_hostname не задан — просто пропускаем без ошибки.
if [[ -n "${meta_hostname:-}" ]]; then
  hostname "$meta_hostname" 2>/dev/null || true
fi

# ➍ Стартовые метки в лог — удобны при разборе проблем/трассировке.
log "== $(date -Is) :: start deploy (OS=${OS}) =="
log "CONFIG: disks ${min_size_gb}-${max_size_gb} GiB, esp=${esp_mb}MiB boot=${boot_mb}MiB swap=${swap_mb}MiB vg=${vg_name}"
log "CONFIG: use_varlog_disk=${use_varlog_disk}"
log "CONFIG: meta_hostname=${meta_hostname:-<unset>}"

