#    чтобы быстрее отличать SSD/HDD при ручной проверке.
#
# 2) Добавить переменную ожидаемого КОЛИЧЕСТВА системных дисков (например,
#      sys_count=2
#    ) и валидировать, что найдено ровно столько; при несовпадении — return 1
#    с понятным сообщением.
#
# 3) Поддержать явные исключения/включения по серийникам (whitelist/blacklist),
#    если на стенде много однотипных дисков и выбор по размеру/типу недостаточен.
