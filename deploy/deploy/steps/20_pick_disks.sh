#!/bin/bash
# =============================================================================
# steps/20_pick_disks.sh — выбор дисков для системы и (опционально) под /var/log
# Версия: v1.2.0
# Дата:   2026-07-23
# -----------------------------------------------------------------------------
# Назначение шага:
#   Определить, на каких дисках будет развёрнута система, и при необходимости
#   подобрать отдельный диск под /var/log.
#
# Что делает:
#   1) pick_system_disks:
#        выбираем «системные» диски по диапазону размеров (см. min_size_gb /
#        max_size_gb в install.env).
#
#   2) filter_disks_by_type:
#        фильтруем найденные системные диски по типу накопителя (см.
#        TARGET_DISK_TYPE / EXCLUDE_DISK_TYPE в install.env), берём максимум два.
#
#   3) Если включён use_varlog_disk=true:
#        подбираем кандидатов под /var/log по своему диапазону varlog_min_gb /
#        varlog_max_gb, исключая уже выбранные системные диски (исходная логика).
#
# Контекст / предпосылки:
#   - Функции pick_system_disks / pick_varlog_disks / filter_disks_by_type
#     определены в lib/disk.sh и подключены через runner.sh.
#   - Параметры min_size_gb, max_size_gb, use_varlog_disk, varlog_min_gb,
#     varlog_max_gb, TARGET_DISK_TYPE, EXCLUDE_DISK_TYPE заданы в install.env.
#   - Шаг исполняется через `source` из runner.sh, поэтому для «ошибки»
#     используется `return 1` (а не `exit`), чтобы не убить весь процесс оболочки.
#
# Результат:
#   - Массив TARGET заполняется именами выбранных системных дисков (sda, nvme0n1, …).
#   - При use_varlog_disk=true массив VARLOG содержит кандидатов под /var/log.
# =============================================================================

# ------------------------ Поиск системных дисков ------------------------------
# 1. Получаем список физических дисков в заданном диапазоне размеров
mapfile -t RAW_SYS < <(pick_system_disks)

# 2. Фильтруем полученные системные диски по типу (TARGET_DISK_TYPE / EXCLUDE_DISK_TYPE)
mapfile -t SYS < <(filter_disks_by_type "${RAW_SYS[@]}")

# Если ничего не нашли в заданном диапазоне с учётом фильтра — лог и мягкий отказ шага.
((${#SYS[@]}>=1)) || { log "No suitable system disks in ${min_size_gb}-${max_size_gb} GiB (TARGET_TYPE=${TARGET_DISK_TYPE:-auto}, EXCLUDE_TYPE=${EXCLUDE_DISK_TYPE:-none})"; return 1; }

# Берём первый и (если есть) второй диск — как кандидаты под одиночную установку
# или зеркалирование (md RAID1). Массив TARGET виден последующим шагам.
TARGET=("${SYS[@]:0:2}")
log "System disks: ${TARGET[*]}"

# ---------------------- Кандидаты под /var/log (опц.) ------------------------
# Если вынесение /var/log включено — ищем подходящие диски по своему диапазону.
# Важно: из поиска исключаем уже выбранные системные диски. Логика не менялась.
if [[ "${use_varlog_disk}" == "true" ]]; then
  # Передаём в pick_varlog_disks строку с именами «занятых» дисков, окружённую пробелами,
  # чтобы простая подстроковая проверка сработала корректно (см. реализацию).
  mapfile -t VARLOG < <(pick_varlog_disks " ${TARGET[*]} ")

  # Лаконичный лог: либо список кандидатов, либо «none».
  ((${#VARLOG[@]})) && log "VARLOG candidates: ${VARLOG[*]}" || log "VARLOG candidates: none"
fi

