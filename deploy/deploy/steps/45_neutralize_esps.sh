#!/bin/bash
# =============================================================================
# 45_neutralize_esps.sh — зачистка «чужих» EFI-загрузчиков на остальных ESP
# Версия: v1.0.1
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   После разметки и монтирования у нас есть «свои» ESP (одна — при одном диске,
#   две — при двух дисках). Здесь мы «обезвреживаем» прочие ESP на машине:
#   переименовываем их метку и удаляем каталоги EFI/BOOT, EFI/ALT, EFI/GRUB, EFI/grub.
#   Это снижает риск, что прошивка/загрузчик подхватят старые записи с других дисков.
#
# Как работает:
#   - Использует neutralize_other_esps() из lib/efi.sh и передаёт ей список ESP,
#     которые НЕЛЬЗЯ трогать (наши).
#   - Функция сама находит все разделы типа ESP по GUID и обрабатывает «лишние».
#
# Предпосылки:
#   - При 2 дисках в шаге 30 уже выставлены переменные d1p1 и d2p1 (ESP каждого диска).
#   - При 1 диске в шаге 30 выставлена переменная p1 (ESP единственного диска).
#   - Массив TARGET определён в шаге 20 (pick_disks).
#   - lib/efi.sh подключен в runner.sh до выполнения этого шага.
# =============================================================================

# Удаляем чужие загрузчики на всех ESP, кроме наших.
if ((${#TARGET[@]}>=2)); then
  # Два системных диска: сохраняем наши ESP (d1p1 и d2p1), прочие ESP чистим
  neutralize_other_esps "$d1p1" "$d2p1"
else
  # Один системный диск: сохраняем единственную нашу ESP (p1), прочие ESP чистим
  neutralize_other_esps "$p1"
fi

