#!/bin/bash
# =============================================================================
# steps/10_global_wipe.sh — глобальная зачистка по всей машине
# Версия: v1.0.2
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение шага:
#   Делегирует работу функции global_wipe из lib/wipe.sh.
#   Задача —:
#     • снять swap;
#     • остановить все md-массивы;
#     • деактивировать/удалить LVM;
#     • прибрать dm-маппинги;
#     • дать udev «догнаться».
#   Подробная реализация находится в lib/wipe.sh (global_wipe, log_disk_snapshot).
#
# Когда вызывать:
#   Сразу после предварительного размонтирования/остановки стеков
#   (см. steps/05_cleanup_mounts.sh), перед разметкой дисков и созданием
#   новых md/LVM-структур.
#
# Идемпотентность:
#   Шаг безопасен для повторных запусков: ошибки внешних утилит внутри
#   global_wipe глушатся, и при повторном вызове просто подтверждается
#   «чистое» состояние.
#
# Контекст:
#   - Функции log, global_wipe и log_disk_snapshot подключены из lib/log.sh
#     и lib/wipe.sh в runner.sh до вызова шага.
#   - Переменная WIPE_VERBOSE (optional) может быть выставлена в окружении
#     для более подробной диагностики.
# =============================================================================

# Создание снимка состояния дисков ДО очистки (если включено WIPE_VERBOSE=true)
if [[ "${WIPE_VERBOSE:-}" == "true" ]]; then
  log "Creating Disk Snapshot BEFORE global wipe (WIPE_VERBOSE=true)"
  log_disk_snapshot
fi

# Полная зачистка md/LVM/dm по всей машине
log "Performing global wipe..."
global_wipe

# Создание снимка состояния дисков ПОСЛЕ очистки (если включено WIPE_VERBOSE=true)
if [[ "${WIPE_VERBOSE:-}" == "true" ]]; then
  log "Creating Disk Snapshot AFTER global wipe (WIPE_VERBOSE=true)"
  log_disk_snapshot
fi

