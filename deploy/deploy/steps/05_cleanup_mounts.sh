#!/bin/bash
# =============================================================================
# steps/05_cleanup_mounts.sh — «обнуление» окружения перед разметкой
# Версия: v1.0.1
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Без перезагрузки привести узел к максимально «чистому» состоянию перед
#   разметкой и развёртыванием:
#     1) размонтировать всё, что относится к целевой системе (/mnt/target и рядом),
#     2) выключить swap,
#     3) остановить все md-массивы (включая autodiscover через --scan),
#     4) деактивировать LVM и снести dm-маппинги,
#     5) дать udev «догнаться».
#
# Почему это важно:
#   Повторный запуск инсталляции без реального ребута часто упирается в
#   «висящие» монтирования и активные стеки md/LVM/dm. Этот шаг подчистит
#   «хвосты», чтобы дальнейшая зачистка/разметка прошла без конфликтов.
#
# Контекст:
#   - Скрипт вызывается из runner.sh уже после 00_env.sh.
#   - Функция log() доступна из lib/log.sh (подключено в runner.sh).
#   - Ожидается наличие утилит: mountpoint, awk, sort, mdadm, vgs/lvremove/vgremove,
#     dmsetup, udevadm.
# =============================================================================

set -euo pipefail

log "[CLEANUP] unmount leftovers and stop stacks"

# 1) Отмонтировать всё под /mnt/target (включая вложенные точки монтирования).
#    Идём «снизу вверх» (reverse sort), чтобы сначала снять подкаталоги.
if mountpoint -q /mnt/target; then
  # Получаем список всех mountpoints, начинающихся с /mnt/target, реверсируем порядок
  awk '$2 ~ "^/mnt/target"' /proc/mounts | awk '{print $2}' | sort -r | while read -r m; do
    # Пытаемся штатный umount; если занято — ленивый umount -l; в любом случае — не валим скрипт
    umount "$m" 2>/dev/null || umount -l "$m" 2>/dev/null || true
  done
fi

# На всякий случай — отдельные точки, которые могли монтироваться вне /mnt/target:
# /boot/efi2, /boot/efi, /boot и /var/log (если /var/log выносили на отдельный диск).
for m in /boot/efi2 /boot/efi /boot /var/log; do
  mountpoint -q "$m" && (umount "$m" 2>/dev/null || umount -l "$m" 2>/dev/null || true)
done

# 2) Выключить swap (если он активен) — иначе блочные устройства могут оставаться «заняты».
swapoff -a 2>/dev/null || true

# 3) Остановить все md-массивы.
#    Перебираем явные /dev/md* и дополнительно командой --scan (на случай автособранных массивов).
for md in /dev/md*; do
  [[ -e "$md" ]] && mdadm --stop "$md" 2>/dev/null || true
done
mdadm --stop --scan 2>/dev/null || true

# 4) Деактивировать все VG, затем жёстко убрать LV и сами VG, и очистить dm-маппинги.
vgchange -an 2>/dev/null || true
for vg in $(vgs --noheadings -o vg_name 2>/dev/null | awk '{print $1}'); do
  lvremove -f "$vg" 2>/dev/null || true
  vgremove -f "$vg" 2>/dev/null || true
done
dmsetup remove --force --retry /dev/mapper/* 2>/dev/null || true

# 5) Дать udev время обработать события удаления/размонтирования,
#    чтобы следующие шаги не наткнулись на «старые» ноды.
udevadm settle || true
sleep 0.5

