#      findmnt -R /mnt/target
#    чтобы в логе сохранялась полная картина исходного состояния.
#
# 2) При «busy» монтированиях опционально убивать держателей (через fuser -vm
#    или lsof), за флагом CLEANUP_KILL_HOLDERS=true, чтобы агрессивнее
#    очищать окружение при отладке.
#
# 3) Вести счётчик/таймаут попыток mdadm --stop --scan и dmsetup remove,
#    логировать случаи, когда стек не удаётся погасить за отведённое время,
#    чтобы проще было диагностировать «флапающие» окружения.
# -----------------------------------------------------------------------------

