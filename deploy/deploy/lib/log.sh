#!/bin/bash
# =============================================================================
# lib/log.sh — модуль логирования для инсталлятора
# Версия: v1.0.2
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Единая точка логирования для всех скриптов пайплайна.
#
# Что даёт:
#   - log(): стандартный логгер с единым форматом сообщений (ISO-время, уровень).
#   - log_level(): логгер с явным уровнем и опциональным именем шага (STEP_NAME).
#   - switch_log_to_target(): переключает вывод с LiveCD-лога на лог внутри
#       целевой установленной системы, подтягивая «ранний» лог.
#
# Контекст:
#   - Переменные early_log и target_log задаются в install.env и уже экспортированы.
#   - Глобальная переменная STEP_NAME (опционально) может быть установлена
#     (например, runner.sh выставляет её по имени текущего шага).
# =============================================================================

# -------------------------- log_level() ---------------------------------------
# Логгер с поддержкой уровня и имени шага.
#
# Аргументы:
#   $1  — уровень (INFO/WARN/ERROR/DEBUG и т.п.);
#   $2+ — текст сообщения.
#
# Формат:
#   [YYYY-MM-DDThh:mm:ss±TZ] [LEVEL] [STEP_NAME] message
#   STEP_NAME добавляется, только если глобальная переменная STEP_NAME задана.
log_level(){
  local level="$1" message="${*:2}" prefix
  
  prefix="[$(date -Is)] [${level}]"
  
  # Добавляем имя шага, если оно установлено (например, в runner.sh)
  if [[ -n "${STEP_NAME:-}" ]]; then
    prefix="${prefix} [${STEP_NAME}]"
  fi
  
  echo "${prefix} ${message}"
}

# ------------------------------ log() -----------------------------------------
# Стандартный логгер по умолчанию.
# Совместим со старым интерфейсом: log "message".
# Уровень жёстко задан как INFO.
log(){ log_level "INFO" "$@"; }

# ---------------------- switch_log_to_target() --------------------------------
# Переключение лога на «целевой» файл внутри установленной системы.
#
# Логика:
#   1) Создать каталог /mnt/target/root (если ещё нет).
#   2) При наличии «раннего» лога (early_log) — дописать его в target_log.
#   3) Перенаправить ВСЁ дальнейшее stdout/stderr текущего процесса в target_log,
#      одновременно дублируя вывод в консоль (tee -a).
#
# Важно:
#   - exec > >(tee -a "$target_log") 2>&1 — одноразовое перенаправление:
#     после вызова функция не возвращает управление в прежнюю схему вывода.
#   - cat "$early_log" >> "$target_log" 2>/dev/null || true — если раннего
#     лога нет или он пуст, установка не падает (ошибка глушится).
switch_log_to_target(){
  mkdir -p /mnt/target/root
  cat "$early_log" >> "$target_log" 2>/dev/null || true
  exec > >(tee -a "$target_log") 2>&1
  log "log switched to $target_log"
}

