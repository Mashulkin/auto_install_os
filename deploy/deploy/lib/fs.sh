#!/bin/bash
# =============================================================================
# lib/fs.sh — мини-утилиты для форматирования файловых систем и безопасного
#              размонтирования перед mkfs.
# Версия: v1.0.2
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Набор вспомогательных функций для:
#     • аккуратного размонтирования устройств перед пересозданием ФС;
#     • зачистки старых сигнатур (wipefs);
#     • создания файловых систем vfat/ext4/xfs с единым логированием.
#
# Что здесь есть:
#   - umount_if(<dev>):
#       если устройство смонтировано — размонтировать (с fallback на umount -l).
#
#   - mkfs_vfat(<dev>, <label>):
#       создание FAT32 (обычно для ESP/EFI-разделов) с заданной меткой.
#
#   - mkfs_ext4(<dev>, <label>, [extra-opts]):
#       создание ext4 с возможностью передать дополнительные опции mkfs.ext4.
#
#   - mkfs_xfs(<dev>, <label>):
#       создание xfs с заданной меткой.
#
# Замечания:
#   • Перед созданием ФС всегда пробуем размонтировать устройство (на случай,
#     если его подцепили автоматически) и зачистить сигнатуры через wipefs -a.
#   • Ошибки wipefs не критичны (например, «сигнатур не найдено») — глушим.
#   • Для ext4 поддержаны «доп. опции» (например, "-E lazy_itable_init=0").
#   • Все операции логируются через log(), чтобы было легко воспроизвести схему.
# =============================================================================

# --------------------------- Размонтирование ----------------------------------
# Размонтировать устройство, если оно где-то смонтировано.
# findmnt -rno TARGET --source <dev> вернёт точку монтирования или пусто.
umount_if() {
  local dev="$1"
  local m
  m=$(findmnt -rno TARGET --source "$dev" 2>/dev/null || true)
  if [[ -n "$m" ]]; then
    log "Attempting to unmount ${m} (device ${dev})"
    # Пробуем штатное размонтирование, если не вышло — ленивое (-l)
    umount "$m" 2>/dev/null || umount -l "$m" 2>/dev/null || true
  fi
}

# ------------------------------- FAT32 ----------------------------------------
# Создать FAT32 (ESP/EFI и т.п.).
#
# Параметры:
#   dev  — /dev/XXX
#   lbl  — метка ФС (до 11 символов для FAT)
mkfs_vfat() {
  local dev="$1" lbl="$2"
  log "Creating vfat on ${dev} with label ${lbl}"
  umount_if "$dev"                       # на всякий — размонтировать
  wipefs -a "$dev" || true               # снять старые сигнатуры (если были)
  mkfs.fat -I -F32 -f2 -n "$lbl" "$dev"  # -I — игнорировать «необычный» размер,
                                         # -F32 — FAT32, -f2 — две копии FAT
}

# -------------------------------- ext4 ----------------------------------------
# Создать ext4.
#
# Параметры:
#   dev    — /dev/XXX
#   lbl    — метка ФС
#   extra  — (необяз.) дополнительные флаги mkfs.ext4, строкой
#            (например, "-E stride=32")
mkfs_ext4() {
  local dev="$1" lbl="$2" extra="${3:-}"
  log "Creating ext4 on ${dev} with label ${lbl} (options: ${extra:-<none>})"
  umount_if "$dev"                       # на всякий — размонтировать
  wipefs -a "$dev" || true               # снять старые сигнатуры
  mkfs.ext4 -q -L "$lbl" $extra "$dev"   # -q — тихий режим, -L — метка
}

# --------------------------------- XFS ----------------------------------------
# Создать xfs.
#
# Параметры:
#   dev  — /dev/XXX
#   lbl  — метка ФС
mkfs_xfs() {
  local dev="$1" lbl="$2"
  log "Creating xfs on ${dev} with label ${lbl}"
  umount_if "$dev"                       # на всякий — размонтировать
  wipefs -a "$dev" || true               # снять старые сигнатуры (если были)
  mkfs.xfs -f -L "$lbl" "$dev"           # -L — метка
}

