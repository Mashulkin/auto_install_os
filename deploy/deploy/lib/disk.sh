#!/bin/bash
# =============================================================================
# lib/disk.sh — утилиты для работы со списком дисков и построения имён разделов
# Версия: v1.3.1
# Дата:   2026-07-23
# -----------------------------------------------------------------------------
# Назначение:
#   Набор вспомогательных функций для:
#     • построения корректных путей к разделам (sda3 / nvme0n1p3 / mmcblk0p2);
#     • получения списка физических дисков (TYPE=disk);
#     • автоматического выбора «системных» дисков по диапазону размеров (GiB)
#       с приоритетным обнаружением виртуальных томов аппаратных RAID-контроллеров;
#     • выбора дисков под /var/log по диапазону размеров, исключая уже занятые;
#     • фильтрации кандидатов по типу накопителя (SATA/SAS vs NVMe).
#
# Что здесь есть:
#   - part_path(<dev>, <n>):
#       вернуть корректный путь к разделу N для устройства, независимо от его
#       типа (sda3 vs nvme0n1p3 vs mmcblk0p2).
#
#   - _get_physical_disks():
#       получить список «настоящих» дисков (TYPE=disk), без md/dm/loop/zram/sr и т.п.
#
#   - pick_system_disks():
#       выбрать «системные» диски по диапазону размеров (GiB). Если обнаружен
#       аппаратный RAID-том, автоматически возвращается только он.
#
#   - pick_varlog_disks(<used_list>):
#       выбрать диски под /var/log по размеру, исключая уже занятые «системные»
#       (список occupied-дисков передаётся аргументом).
#
#   - filter_disks_by_type(<disks_array...>):
#       отфильтровать переданный список дисков согласно правилам TARGET_DISK_TYPE
#       и EXCLUDE_DISK_TYPE из install.env (вывод по одному диску на строку).
#
# Предпосылки:
#   - Переменные min_size_gb, max_size_gb, varlog_min_gb, varlog_max_gb,
#     TARGET_DISK_TYPE, EXCLUDE_DISK_TYPE задаются в install.env и уже
#     экспортированы к моменту вызова.
#   - lsblk доступен в окружении LiveCD.
# =============================================================================

# ------------------------- Построение имени раздела ---------------------------
# Вернуть путь к разделу независимо от типа устройства.
#
# Примеры:
#   part_path sda 3        -> /dev/sda3
#   part_path nvme0n1 1    -> /dev/nvme0n1p1
#   part_path mmcblk0 2    -> /dev/mmcblk0p2
part_path(){
  local d="$1" n="$2"
  # У NVMe и MMC разделы имеют суффикс 'pN', у остальных — просто 'N'
  [[ "$d" =~ ^(nvme|mmcblk) ]] && echo "/dev/${d}p${n}" || echo "/dev/${d}${n}"
}

# ----------------------- Фильтрация «настоящих» дисков -----------------------
# Получить список базовых устройств, которые действительно являются дисками.
#
# Используем:
#   lsblk -dn -o NAME,TYPE
#   и оставляем только строки с TYPE=disk — это автоматически исключает:
#     - md* (mdadm RAID),
#     - dm-* (device-mapper),
#     - loop*,
#     - zram*,
#     - sr* (CD/DVD),
#     - и прочие псевдоустройства.
_get_physical_disks() {
  lsblk -dn -o NAME,TYPE | awk '$2=="disk"{print $1}'
}

# ------------------------ Выбор «системных» дисков ---------------------------
# Выбрать «системные» диски по диапазону размеров (в GiB) с умным приоритетом
# аппаратных RAID-контроллеров.
#
# Логика:
#   - Перебираем физические диски и отбираем те, что попадают в [min_size_gb..max_size_gb].
#   - Опрашиваем MODEL и VENDOR у кандидатов.
#   - Если находится диск с признаками аппаратного RAID (Broadcom/MegaRAID/PERC/SmartArray),
#     скрипт отдаёт ему высший приоритет и возвращает ТОЛЬКО его (1 виртуальный том).
#   - Если аппаратных RAID нет — возвращается стандартный список под mdadm RAID1.
#
# Возврат:
#   - Список имён устройств на stdout (по одному в строке), либо пустой вывод.
pick_system_disks(){
  local list=() hw_raid_list=() d size_b gb model_vendor

  for d in $(_get_physical_disks); do
    # Размер диска в байтах
    size_b=$(lsblk -dn -b -o SIZE "/dev/$d" 2>/dev/null || echo 0)
    gb=$(( size_b / 1024 / 1024 / 1024 ))

    if (( gb>=min_size_gb && gb<=max_size_gb )); then
      list+=("$d")

      # Проверка сигнатур аппаратных RAID-контроллеров по MODEL и VENDOR
      model_vendor=$(lsblk -dno MODEL,VENDOR "/dev/$d" 2>/dev/null)
      if [[ "$model_vendor" =~ (MR[0-9]|MegaRAID|BROADCOM|PERC|LOGICAL[[:space:]]+VOLUME|Smart[[:space:]]+Array|AVAGO|LSI|Adaptec|Virtual[[:space:]]+Disk) ]]; then
        hw_raid_list+=("$d")
      fi
    fi
  done

  # Если найден хотя бы один аппаратный RAID — отдаем приоритет только ему
  if ((${#hw_raid_list[@]})); then
    printf "%s\n" "${hw_raid_list[0]}"
  elif ((${#list[@]})); then
    printf "%s\n" "${list[@]}"
  fi
}

# ----------------------- Выбор дисков под /var/log ----------------------------
# Выбрать диски под /var/log по диапазону размеров (в GiB),
# исключая уже использованные «системные» диски.
#
# Аргументы:
#   $1 — used: строка с именами занятых дисков, разделённых пробелами
#              (например: "sda nvme0n1").
#
# Логика:
#   - Перебираем все физические диски.
#   - Пропускаем те, что присутствуют в списке used.
#   - Для остальных проверяем размер на попадание в [varlog_min_gb..varlog_max_gb].
#   - Подходящие устройства добавляем в результат.
#
# Возврат:
#   - Список имён подходящих устройств на stdout (по одному в строке),
#     либо пустой вывод, если подходящих дисков нет.
pick_varlog_disks(){
  local used="$1" list=() d size_b gb
  for d in $(_get_physical_disks); do
    # Если диск уже отмечен как использованный — пропускаем
    [[ " $used " == *" $d "* ]] && continue
    size_b=$(lsblk -dn -b -o SIZE "/dev/$d" 2>/dev/null || echo 0)
    gb=$(( size_b / 1024 / 1024 / 1024 ))
    (( gb>=varlog_min_gb && gb<=varlog_max_gb )) && list+=("$d")
  done
  ((${#list[@]})) && printf "%s\n" "${list[@]}"
}

# ----------------------- Фильтр дисков по типу --------------------------------
# Фильтрация массива дисков по типу устройства (sd vs nvme).
#
# Аргументы:
#   $@ — список дисков/путей к дискам (например: "sda sdb nvme0n1" или "/dev/sda /dev/nvme0n1").
#
# Использует глобальные переменные из install.env:
#   - EXCLUDE_DISK_TYPE: nvme | sd | none
#   - TARGET_DISK_TYPE:  nvme | sd | auto
#
# Возврат:
#   - Отфильтрованный список устройств на stdout (по одному имени на строку).
filter_disks_by_type() {
    local input_disks=("$@")
    local filtered=()

    for d in "${input_disks[@]}"; do
        local dev_name
        dev_name=$(basename "$d")

        # 1. Проверка правил исключения (EXCLUDE_DISK_TYPE)
        if [ "${EXCLUDE_DISK_TYPE:-none}" = "nvme" ] && [[ "$dev_name" == nvme* ]]; then
            continue
        fi
        if [ "${EXCLUDE_DISK_TYPE:-none}" = "sd" ] && [[ "$dev_name" == sd* ]]; then
            continue
        fi

        # 2. Проверка целевого типа (TARGET_DISK_TYPE)
        if [ "${TARGET_DISK_TYPE:-auto}" = "nvme" ] && [[ "$dev_name" != nvme* ]]; then
            continue
        fi
        if [ "${TARGET_DISK_TYPE:-auto}" = "sd" ] && [[ "$dev_name" != sd* ]]; then
            continue
        fi

        filtered+=("$d")
    done

    # Печатаем по одному элементу на строку, чтобы не слипались в одну строку
    ((${#filtered[@]})) && printf "%s\n" "${filtered[@]}"
}

