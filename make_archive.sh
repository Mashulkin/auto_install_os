#!/usr/bin/env bash
# =============================================================================
# make_archive.sh — создание полного архива системы для развёртывания
# Версия: v2.0.1
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Снять полный tgz-архив текущей системы (root.tgz) для последующего
#   развёртывания на целевой машине.
#
# Что именно делает скрипт:
#   • Создаёт tgz-архив (root.tgz), включающий:
#       - корневую ФС (/),
#       - /boot,
#       - /var (если /var — отдельная ФС).
#   • Исключает:
#       - lost+found,
#       - /mnt/*,
#       - сам каталог назначения DEST_DIR и его содержимое.
#   • НЕ исключает /home — домашние каталоги пользователей попадают в архив.
#   • Использует --one-file-system:
#       - для блока -C / . это ограничивает архив одной ФС (root),
#       - для -C /boot и -C /var каждую ФС архивируем отдельно.
#
# Важно:
#   • Скрипт предполагает, что исходная система уже имеет ту же структуру
#     разделов, что и боевая (минимум: отдельный /boot, по желанию — отдельный
#     /var). Тогда в архиве не будет «опасных» hardlink-ов между / и /var,
#     и его можно безопасно разворачивать на уже смонтированные FS.
#   • Архив предназначен для последующего развёртывания средствами
#     auto_install.sh / deploy.sh — структура и имя root.tgz согласованы с ними.
# =============================================================================

set -euo pipefail

# Каталог, куда положим готовый архив.
# Обычно это заранее смонтированный recovery-раздел или внешний носитель.
DEST_DIR="/mnt/recovery"

# Имя (без расширения) будущего архива
BASENAME="root"

# Выбор компрессора: по умолчанию gzip; если есть pigz — используем его
COMPRESSOR="gzip"
if command -v pigz >/dev/null 2>&1; then
  COMPRESSOR="pigz"
fi

# Создаём каталог назначения (тихо, если уже есть)
mkdir -p "$DEST_DIR"

# Полный путь к архиву
ARCHIVE="$DEST_DIR/${BASENAME}.tgz"

echo "[*] Создаю архив: $ARCHIVE"
echo "[*] Компрессор: $COMPRESSOR"
echo "[*] В архив войдут: /, /boot и (при отдельной ФС) /var"
echo "[*] Исключения: lost+found, /mnt/*, $DEST_DIR/*"

# -----------------------------------------------------------------------------
# Формируем аргументы для tar в виде массива, чтобы удобно добавлять /var
# -----------------------------------------------------------------------------

TAR_ARGS=(
  -cp                # создать архив, сохранить права (как -p в старом варианте)
  --force-local      # обрабатывать имя архива как локальный файл
  --numeric-owner    # записывать владельцев как числовые UID/GID
  --one-file-system  # не переходить на другие ФС в рамках одного -C <dir> .
  --exclude='lost+found'
  --exclude="/mnt/*"
  --exclude="${DEST_DIR}/*"
)

# 1) Корень ФС:
#    -C / . — начать из корня и архивировать всё, что живёт на той же FS, что и /
#    (из-за --one-file-system сюда НЕ попадут /boot и /var, если они отдельные).
TAR_ARGS+=( -C / . )

# 2) /boot:
#    Здесь предполагается, что /boot — отдельная ФС или подкаталог на той же ФС.
#    -C / boot добавляет дерево /boot в архив. Благодаря --one-file-system tar
#    не пойдёт в другие ФС, смонтированные внутри /boot (если такие есть).
TAR_ARGS+=( -C / boot )

# 3) /var:
#    Если /var — отдельная ФС, то содержимое /var НЕ попало в блок -C / .
#    В этом случае мы отдельно добавим его в тот же архив:
if findmnt -n /var >/dev/null 2>&1; then
  echo "[*] Обнаружено, что /var является отдельной ФС. Добавляю /var в архив отдельно."
  # -C / var — здесь /var является точкой входа в свою ФС;
  # из-за --one-file-system в архив попадёт только содержимое этой ФС.
  TAR_ARGS+=( -C / var )
else
  echo "[*] /var НЕ является отдельной ФС. Его содержимое уже попадёт в блок -C / ."
fi

# -----------------------------------------------------------------------------
# Сбор содержимого в tar-поток и сжатие
#
# Объяснение по важным опциям:
#  -cp              : создать архив, сохранить права (permissions)
#  --force-local    : обрабатывать имена как локальные файлы
#  --numeric-owner  : писать UID/GID вместо имён пользователей/групп
#  --one-file-system:
#      • при -C / .   — остаёмся в пределах корневой ФС,
#      • при -C / boot — остаёмся в пределах ФС /boot,
#      • при -C / var  — остаёмся в пределах ФС /var.
#  --exclude=...    : исключаем мусор и сам каталог назначения.
#
# -----------------------------------------------------------------------------

tar "${TAR_ARGS[@]}" | $COMPRESSOR -c > "$ARCHIVE"

# Краткая сводка о размере получившегося файла
SIZE=$(du -h "$ARCHIVE" | awk '{print $1}')
echo
echo "[✓] Готово: $ARCHIVE ($SIZE)"
echo
echo "Проверка содержимого (первые строки):"
echo "  tar -tzf \"$ARCHIVE\" | head"
echo
echo "Проверка, что /boot попал в архив:"
echo "  tar -tzf \"$ARCHIVE\" | grep '^boot/' | head || echo 'В архиве не найден каталог boot/'"
echo
echo "Если /var — отдельная ФС, можно проверить его содержимое в архиве так:"
echo "  tar -tzf \"$ARCHIVE\" | grep '^var/' | head || echo 'var/ не найден или /var не был отдельной ФС при создании архива.'"

# -----------------------------------------------------------------------------
# Предложения по улучшению (идеи, код выше НЕ меняется):
#
# 1) Вынести список исключений (кеши, временные файлы и т.п.) в отдельный файл
#    и подключать через --exclude-from.
#
# 2) Для больших систем рассмотреть использование zstd:
#      COMPRESSOR="pzstd" или "zstd -T0"
#    и использовать расширение .tar.zst.
#
# -----------------------------------------------------------------------------

