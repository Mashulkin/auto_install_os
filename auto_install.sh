#    (например, параметры ip=..., repo=...), чтобы одним initrd обслуживать
#    разные площадки/хранилища.
#
# 3) Логировать версию бандла (например, файл VERSION внутри архива) и
#    записывать её в лог, чтобы можно было отследить, каким именно релизом
#    ставилась конкретная машина.
#
# 4) Реализовать опциональный fallback на HTTP(S)-скачивание (curl/wget),
