#!/bin/bash
# =============================================================================
# auto_install.sh — автоматическое развёртывание из бандла на LiveCD
# Версия: v1.0.1
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   ЕДИНСТВЕННАЯ точка входа на LiveCD для автоматической установки.
#
#   Скрипт выполняет три основных шага:
#     1) Скачивает файл install.env из единого удалённого хранилища.
#     2) Подгружает из него переменные окружения и выставляет минимум
#        параметров, ожидаемых шагами (backup_ip, backup_passwd, backup_dir).
#     3) Скачивает бандл установщика (deploy.bundle.tar.gz) из того же места,
#        распаковывает его в /root/deploy и передаёт управление runner.sh.
#
# Важно:
#   • Координаты удалённого хранилища (SERVER_IP, REMOTE_BASE и т.п.)
#     жёстко заданы только здесь (условие «курица/яйцо»).
#   • Вся изменчивая логика (выбор ОС, каталог бэкапа и пр.) вынесена
#     в install.env, который поддерживается отдельно.
#   • Лог работы пишется в /tmp/deploy.log (удобно смотреть прямо на LiveCD).
# =============================================================================

# Жёсткий режим оболочки:
#   -e             — немедленно завершать скрипт при любой ненулевой ошибке
#   -u             — считать обращение к несуществующим переменным ошибкой
#   -o pipefail    — возвращать код ошибки конвейера, если упала ЛЮБАЯ команда
set -euo pipefail
# Безопасный IFS: отделяем поля переводом строки и табом (защита от пробелов в путях)
IFS=$'\n\t'

# --------------------------- Глобальный лог -----------------------------------
# Дублируем весь вывод и в консоль, и в файл /tmp/deploy.log.
# Это позволяет:
#   • видеть текущий прогресс в терминале;
#   • разбирать лог постфактум при отладке.
LOG="/tmp/deploy.log"
exec > >(tee -a "$LOG") 2>&1
echo "== $(date -Is) :: auto_install started =="

# ------------------ ЕДИНСТВЕННОЕ место хранения (фикс) -----------------------
# Здесь лежат:
#   • install.env;
#   • deploy.bundle.tar.gz;
#   • каталоги с бэкапами (используются уже внутри шагов).
#
# ВАЖНО: Эти значения задают «координаты» хранилища. При переносе/смене
# сервера их меняют только здесь.
SERVER_IP="10.3.15.250"
SERVER_USER="root"
SERVER_PASS="root"
REMOTE_BASE="/backup/deploy"
BUNDLE_NAME="deploy.bundle.tar.gz"

# ---------------------------- Функции -----------------------------------------
# Универсальная функция скачивания файла (scp через sshpass).
# Используем sshpass, чтобы не требовать ключи на LiveCD, и отключаем
# StrictHostKeyChecking (хост в каждом запуске может считаться «новым»).
pull() {
  local src="$1" dst="$2"
  echo "[pull] ${SERVER_USER}@${SERVER_IP}:${src} -> ${dst}"
  sshpass -p "$SERVER_PASS" scp -o StrictHostKeyChecking=no -q \
    "${SERVER_USER}@${SERVER_IP}:${src}" "${dst}"
}

# --------------------------- Шаг 1. install.env ------------------------------
# Забираем install.env и экспортируем параметры из него в окружение текущей сессии.
TMP_ENV="/tmp/install.env.$$"
pull "${REMOTE_BASE}/install.env" "$TMP_ENV"

# set -a включает автоэкспорт всех последующих присваиваний из файла
set -a
# shellcheck:disable=SC1090 — подключаем файл по пути из переменной (динамический source)
. "$TMP_ENV"
set +a
rm -f "$TMP_ENV"

# Минимальная валидация: ensure OS/backup_dir заданы в install.env.
: "${OS:?must be set in install.env}"
: "${backup_dir:?must be set in install.env}"

# Для совместимости со "step"-скриптами выставляем окружение:
# Шаги ожидают переменные backup_ip/backup_passwd; берём их из «единого места».
export backup_ip="${SERVER_IP}"
export backup_passwd="${SERVER_PASS}"
# (backup_dir уже пришёл из install.env и был экспортирован выше)

# --------------------------- Шаг 2. Бандл ------------------------------------
# Скачиваем архив с самим установщиком и распаковываем его в /root/deploy.
TMP_BUNDLE="/tmp/${BUNDLE_NAME}"
pull "${REMOTE_BASE}/${BUNDLE_NAME}" "$TMP_BUNDLE"

# Чистим старую раскладку (если была) и разворачиваем свежую.
rm -rf /root/deploy 2>/dev/null || true
tar -xzf "$TMP_BUNDLE" -C /root
rm -f "$TMP_BUNDLE"

# --------------------------- Шаг 3. Запуск -----------------------------------
# Главный раннер, который уже разрулит шаги под конкретную ОС.
echo "[exec] /root/deploy/runner.sh (OS=${OS})"
exec /root/deploy/runner.sh

