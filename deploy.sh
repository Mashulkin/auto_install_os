#!/bin/bash
# =============================================================================
# deploy.sh — сборка бандла установщика
# Версия: v1.0.1
# Дата:   2025-12-11
# -----------------------------------------------------------------------------
# Назначение:
#   Сформировать единый бандл установщика (deploy.bundle.tar.gz), содержащий:
#     • все служебные библиотеки (lib/),
#     • пошаговый пайплайн steps/,
#     • os-специфичные chroot-скрипты,
#     • runner.sh,
#     • install.env.
#
#   Этот бандл используется auto_install.sh на LiveCD для полноценного
#   развертывания системы. Файл deploy.bundle.tar.gz должен находиться
#   в каталоге /backup/deploy.
#
# Как работает упаковка:
#   - Переходим в /backup/deploy.
#   - Упаковываем каталог deploy (целевой верхний уровень в архиве).
#   - Используем tar с компрессией gzip (через -z).
#   - Сохраняются права, владельцы, симлинки и структура подкаталогов.
#
# Важно:
#   • Файл deploy.bundle.tar.gz полностью самодостаточен — он включает все
#     необходимые скрипты и конфиги.
#   • Код упаковки предельно минималистичен и повторяем.
# =============================================================================

cd /backup/deploy

# -----------------------------------------------------------------------------
# Сборка бандла
# -----------------------------------------------------------------------------
tar -czf deploy.bundle.tar.gz -C /backup/deploy deploy

