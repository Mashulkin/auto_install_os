#      deploy.bundle-$(date +%Y%m%d%H%M).tar.gz
#    и обновлять симлинк:
#      ln -sf deploy.bundle-*.tar.gz deploy.bundle.tar.gz
#
# 2) Создавать SHA256-сумму для верификации на стороне LiveCD:
#      sha256sum deploy.bundle.tar.gz > deploy.bundle.tar.gz.sha256
